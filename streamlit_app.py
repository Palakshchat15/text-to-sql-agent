def page_ask():
    st.title("Ask the data warehouse")
    st.caption("Plain-English questions about the flight, fraud, retail and sales warehouses. The agent "
               "retrieves the relevant tables, writes DuckDB SQL with a local model, runs it read-only and "
               "fixes its own errors.")
    with st.sidebar:
        st.subheader("Settings")
        models = CFG["llm"]["models_evaluated"]
        model = st.selectbox("Model (Ollama)", models, index=models.index(CFG["llm"]["model"]))
        configs = [c for c in CFG["ablations"] if c != "oracle_tables_upper"]
        config_name = st.selectbox("Agent configuration", configs, index=configs.index("full_agent"),
                                   help="full_agent = schema retrieval + docs + up to 3 self-corrections.")
    cols = st.columns(3)
    for i, ex in enumerate(EXAMPLES):
        if cols[i % 3].button(ex, key=f"ex{i}", width="stretch"):
            st.session_state["q"] = ex
    q = st.text_input("Question", key="q", placeholder="e.g. Which carrier had the most cancelled flights?")
    go = st.button("Ask", type="primary")
    if go and q.strip():
        from src.llm import OllamaUnavailable

        try:
            with st.spinner(f"Thinking with {model} (on a CPU this can take a few minutes) ..."):
                r = get_agent(config_name, model).ask(q.strip())
            st.session_state["last"] = r
        except OllamaUnavailable as e:
            st.error(str(e))
            return
    r = st.session_state.get("last")
    if r is None:
        st.info("Pick an example or type a question, then press **Ask**. Answers need Ollama running locally "
                f"with `{CFG['llm']['model']}` pulled.")
        return
    st.markdown(f"**Question:** {r.question}")
    if r.status == "refused":
        st.warning(f"Refused: {r.refusal_reason}")
    elif r.status != "ok":
        st.error(f"No answer after {len(r.attempts)} attempt(s): {r.error}")
    else:
        st.success(r.summary)
        df = pd.DataFrame(r.rows, columns=r.columns)
        draw_chart(df, r.chart)
        st.dataframe(df, width="stretch", hide_index=True, height=min(400, 38 + 35 * len(df)))
        if r.truncated:
            st.caption(f"Showing the first {len(df)} rows (maximum result size).")
    if r.sql:
        with st.expander("Generated SQL", expanded=r.status != "ok"):
            st.code(r.sql, language="sql")
    with st.expander(f"Attempts log ({len(r.attempts)})"):
        for a in r.attempts:
            outcome = (f"guardrail block: {a['guard_reason']}" if a["guard_reason"] else
                       f"error: {a['error']}" if a["error"] else
                       f"{a['n_rows']} rows" if a["n_rows"] is not None else "refusal / no SQL")
            st.markdown(f"**Attempt {a['n']}**: {outcome} - LLM {a['t_llm']:.1f}s, "
                        f"{a['prompt_tokens']} prompt + {a['completion_tokens']} completion tokens")
            if a["sql"]:
                st.code(a["sql"], language="sql")
    st.caption(f"Tables given to the model: {', '.join(t for t, _ in r.retrieved[:10])}"
               f"{' ...' if len(r.retrieved) > 10 else ''} | total {r.t_total:.1f}s "
               f"(LLM {r.t_llm:.1f}s, SQL {r.t_exec * 1000:.0f} ms) | model {r.model} | config {r.config}")


