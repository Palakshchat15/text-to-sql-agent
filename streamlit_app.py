def page_eval():
    st.title("Evaluation")
    st.caption("Execution accuracy on a builder-written golden set: 90 questions with verified gold SQL "
               "(15 per difficulty level) + 10 unanswerable questions. Split: dev 30 / test 70, stratified, seed 42.")
    summ = read_csv("summary_test.csv")
    if summ is None:
        st.info("**Test-set evaluation: not run yet.** The batch evaluations run on the GPU machine "
                "(`scripts\\run_queue_task.cmd`). This page fills in automatically once "
                "`results/summary_test.csv` exists.")
    else:
        if not summ["complete"].all():
            st.warning("Some runs are incomplete (n_done < n_split); numbers below are partial.")
        show = summ.copy()
        st.subheader("Ablations (test)")
        st.dataframe(show, width="stretch", hide_index=True)
        import altair as alt

        long = show.melt(id_vars=["config"], value_vars=["exec_acc_answerable", "refusal_acc_unanswerable"],
                         var_name="metric", value_name="value").dropna()
        ch = (alt.Chart(long).mark_bar()
              .encode(y=alt.Y("config:N", title=None, sort=list(show["config"])),
                      x=alt.X("value:Q", scale=alt.Scale(domain=[0, 1]), title=None),
                      color=alt.Color("metric:N", scale=alt.Scale(range=SERIES[:2]),
                                      legend=alt.Legend(orient="top", title=None)),
                      yOffset="metric:N", tooltip=["config", "metric", alt.Tooltip("value:Q", format=".3f")])
              .properties(height=alt.Step(16)))
        st.altair_chart(ch.configure_view(strokeWidth=0), width="stretch")
        bd = read_csv("by_difficulty_test.csv")
        if bd is not None:
            st.subheader("Accuracy by difficulty")
            st.dataframe(bd.pivot(index="difficulty", columns="config", values="accuracy"), width="stretch")
        ea = RES / "error_analysis_test.json"
        if ea.exists():
            st.subheader("Error analysis (rule-based buckets)")
            data = json.loads(ea.read_text(encoding="utf-8"))
            cfg_sel = st.radio("Run", list(data), horizontal=True, key="ea_cfg")
            b = data[cfg_sel]["buckets"]
            st.dataframe(pd.DataFrame([{"bucket": k, "count": v["count"]} for k, v in b.items()]),
                         hide_index=True)
            for k, v in b.items():
                with st.expander(f"{k} ({v['count']})"):
                    for e in v["examples"]:
                        st.markdown(f"**{e['id']}** {e['question']}  \n_{e['reason']}_")
                        st.code(f"-- gold\n{e['gold_sql']}\n-- predicted\n{e['pred_sql']}", language="sql")
        st.subheader("Per-question browser")
        runs = sorted((RES / "scored").glob("test__*.jsonl"))
        if runs:
            run = st.selectbox("Run", [p.stem.split("__", 1)[1] for p in runs])
            rows = read_jsonl(RES / "scored" / f"test__{run}.jsonl")
            df = pd.DataFrame(rows)
            filt = st.radio("Show", ["all", "correct", "wrong"], horizontal=True)
            if filt != "all":
                df = df[df["correct"] == (filt == "correct")]
            st.dataframe(df[["id", "difficulty", "correct", "status", "n_attempts", "t_total", "reason", "question"]],
                         width="stretch", hide_index=True)
            pick = st.selectbox("Question", list(df["id"]))
            if pick:
                r = df[df["id"] == pick].iloc[0]
                st.code(f"-- gold\n{r['gold_sql']}\n-- predicted\n{r['pred_sql']}", language="sql")

    st.subheader("Already available (no LLM needed)")
    c1, c2 = st.columns(2)
    with c1:
        st.markdown("**Schema retrieval on dev** (table recall of gold-SQL tables vs. tables given to the model)")
        rd = read_csv("retrieval_dev.csv")
        if rd is not None:
            st.dataframe(rd, hide_index=True, width="stretch")
            st.caption(f"Chosen on dev: top {CFG['retrieval']['top_tables']} tables.")
    with c2:
        smoke = RES / "smoke_test.json"
        st.markdown("**Smoke test** (a few dev questions end to end; not an evaluation)")
        if smoke.exists():
            sm = pd.DataFrame(json.loads(smoke.read_text(encoding="utf-8")))
            st.dataframe(sm[["id", "model", "status", "correct", "n_attempts", "t_total"]], hide_index=True,
                         width="stretch")
        else:
            st.write("not run yet")
    with st.expander("Golden set (all 100 questions with gold SQL)"):
        g = pd.DataFrame(questions_for("all"))
        splits = json.loads(path("splits").read_text(encoding="utf-8"))
        g["split"] = g["id"].map(lambda i: "dev" if i in set(splits["dev"]) else "test")
        st.dataframe(g[["id", "split", "difficulty", "question", "gold_sql", "gold_rows", "order_matters"]],
                     width="stretch", hide_index=True)


