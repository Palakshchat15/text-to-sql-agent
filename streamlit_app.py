def page_monitor():
    st.title("Monitoring")
    from src.tracing import Tracer

    df = Tracer(path("traces_db")).read()
    if df.empty:
        st.info("No traces yet. Every question asked in the app (and in evaluations) is logged to data/traces.db.")
        return
    src = st.radio("Source", ["all"] + sorted(df["source"].dropna().unique()), horizontal=True)
    if src != "all":
        df = df[df["source"] == src]
    k = st.columns(6)
    k[0].metric("Requests", len(df))
    k[1].metric("Answered", int((df["status"] == "ok").sum()))
    k[2].metric("Refused", int((df["status"] == "refused").sum()))
    k[3].metric("Latency p50", f"{df['t_total'].quantile(0.5):.1f} s")
    k[4].metric("Latency p95", f"{df['t_total'].quantile(0.95):.1f} s")
    k[5].metric("Avg attempts", f"{df['n_attempts'].mean():.2f}")
    df = df.copy()
    # Local time (ts is a Unix timestamp; without this the table showed UTC).
    df["time"] = df["ts"].map(lambda t: datetime.datetime.fromtimestamp(t).strftime("%Y-%m-%d %H:%M:%S"))
    st.dataframe(df[["id", "time", "source", "config", "model", "status", "n_attempts", "guard_blocks", "n_rows",
                     "t_total", "t_llm", "t_exec", "prompt_tokens", "completion_tokens", "question"]],
                 width="stretch", hide_index=True)
    pick = st.selectbox("Trace detail", list(df["id"]))
    if pick is not None:
        r = df[df["id"] == pick].iloc[0]
        st.markdown(f"**{r['question']}** - {r['status']}, {r['n_attempts']} attempt(s)")
        if pd.notna(r["final_sql"]) and r["final_sql"]:   # refusals have no SQL (NaN in the frame)
            st.code(r["final_sql"], language="sql")
        st.json(json.loads(r["attempts"] or "[]"), expanded=False)
        st.caption(f"Retrieved: {r['retrieved']}")


nav = st.navigation([
    st.Page(page_ask, title="Ask", default=True),          # served at the root URL
    st.Page(page_schema, title="Schema explorer", url_path="schema"),
    st.Page(page_eval, title="Evaluation", url_path="evaluation"),
    st.Page(page_monitor, title="Monitoring", url_path="monitoring"),
])
with st.sidebar:
    st.caption(ATTRIBUTION)
nav.run()
