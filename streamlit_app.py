def page_schema():
    st.title("Schema explorer")
    cat = load_catalog()
    schemas = sorted({t["schema"] for t in cat})
    man = pd.read_csv(path("manifest"))
    k = st.columns(4)
    k[0].metric("Schemas", len(schemas))
    k[1].metric("Tables", len(cat))
    k[2].metric("Columns", sum(len(t["columns"]) for t in cat))
    k[3].metric("Rows", f"{int(man['rows'].sum()):,}")
    s = st.radio("Project schema", schemas, horizontal=True)
    tabs = [t for t in cat if t["schema"] == s]
    if tabs and tabs[0].get("project"):
        st.caption(tabs[0]["project"])
    st.dataframe(pd.DataFrame([{"table": t["fq"], "rows": t["rows"], "columns": len(t["columns"]),
                                "description": t["description"]} for t in tabs]),
                 width="stretch", hide_index=True,
                 column_config={"rows": st.column_config.NumberColumn(format="localized")})
    for t in tabs:
        with st.expander(f"{t['fq']}  ({t['rows']:,} rows)"):
            st.markdown(t["description"] or "_No description in dbt._")
            st.dataframe(pd.DataFrame([{"column": c["name"], "type": c["type"], "description": c["description"],
                                        "examples": ", ".join(map(str, c["samples"]))} for c in t["columns"]]),
                         width="stretch", hide_index=True)
    st.caption("Descriptions come from each project's dbt schema.yml plus builder-written notes "
               "(data/column_notes.yaml); types and examples from the DuckDB copy. " + ATTRIBUTION)


