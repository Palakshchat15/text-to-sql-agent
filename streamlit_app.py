@st.cache_resource(show_spinner="Loading schema catalogue and warehouse ...")
def shared():
    from src.executor import Executor
    from src.retrieval import SchemaRetriever

    a = CFG["agent"]
    return SchemaRetriever(), Executor(path("warehouse"), timeout_s=a["timeout_s"], max_rows=a["max_rows"])


def get_agent(config_name: str, model: str):
    from src.agent import Agent

    key = f"agent::{config_name}::{model}"
    if key not in st.session_state:
        retr, ex = shared()
        st.session_state[key] = Agent(config_name, model=model, trace_source="app", retriever=retr, executor=ex)
    return st.session_state[key]


@st.cache_data
def load_catalog():
    return json.loads(path("catalog").read_text(encoding="utf-8"))


def read_csv(name: str) -> pd.DataFrame | None:
    p = RES / name
    return pd.read_csv(p) if p.exists() else None


def read_jsonl(p: Path) -> list[dict]:
    if not p.exists():
        return []
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]


def draw_chart(df: pd.DataFrame, spec: dict) -> None:
    import altair as alt

    if spec.get("type") not in ("bar", "line") or df.empty:
        return
    x, ys = spec["x"], [y for y in spec["y"] if y in df.columns]
    if x not in df.columns or not ys:
        return
    d = df[[x] + ys].copy()
    long = d.melt(id_vars=[x], value_vars=ys, var_name="series", value_name="value")
    color = (alt.Color("series:N", scale=alt.Scale(range=SERIES), legend=alt.Legend(orient="top", title=None))
             if len(ys) > 1 else alt.value(SERIES[0]))
    if spec["type"] == "bar":
        ch = (alt.Chart(long).mark_bar(cornerRadiusEnd=2)
              .encode(y=alt.Y(f"{x}:N", sort="-x", title=None, axis=alt.Axis(labelLimit=260)),
                      x=alt.X("value:Q", title=ys[0], axis=alt.Axis(grid=True, gridOpacity=0.15)),
                      color=color, tooltip=[x, "value"])
              .properties(height=alt.Step(22)))
    else:
        xt = "T" if pd.api.types.is_datetime64_any_dtype(d[x]) or d[x].dtype == object else "O"
        if xt == "T":
            long[x] = pd.to_datetime(long[x])
        ch = (alt.Chart(long).mark_line(point=len(d) <= 40)
              .encode(x=alt.X(f"{x}:{xt}", title=x), y=alt.Y("value:Q", title=None,
                                                              axis=alt.Axis(grid=True, gridOpacity=0.15)),
                      color=color, tooltip=[x, "series", "value"])
              .properties(height=320))
    st.altair_chart(ch.configure_view(strokeWidth=0), width="stretch")


